"""Run from the repository root with Python 3.11 or newer (tomllib):

    /etc/profiles/per-user/$USER/bin/python3 -m unittest modules/herdr/tests/test_sync_config.py

macOS's own /usr/bin/python3 is older and comes first on PATH.
"""

import importlib.util
from pathlib import Path
import tempfile
import tomllib
import unittest


FEATURE = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("herdr_sync", FEATURE / "files/sync-config.py")
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
SOURCE = (FEATURE / "files/config.toml").read_text()

# The table as OmniWM renders it (AppThemeBuiltIn.herdrTemplate).
OMNIWM_TABLE = (
    "[theme.custom]\n"
    "# Generated by OmniWM from its dark palette. OmniWM rewrites this table when the palette changes.\n"
    'accent = "#a8c8ff"\n'
    'panel_bg = "reset"\n'
    'text = "#e2e2e9"\n'
    'teal = "#bcc7dc"\n'
)


def with_table(text, table):
    lines = text.splitlines(keepends=True)
    start, end = module.table_span(lines)
    return "".join(lines[:start]) + table + "".join(lines[end:])


class SyncConfigTests(unittest.TestCase):
    def test_repository_config_is_used_when_nothing_is_installed(self):
        self.assertEqual(module.merge(SOURCE, None), SOURCE)

    def test_live_color_table_survives_byte_for_byte(self):
        live = with_table(SOURCE, OMNIWM_TABLE)
        merged = module.merge(SOURCE, live)
        self.assertEqual(merged, live)
        self.assertIn(OMNIWM_TABLE, merged)

    def test_repository_changes_outside_the_table_still_apply(self):
        live = with_table(SOURCE, OMNIWM_TABLE)
        changed = SOURCE.replace('prefix = "ctrl+b"', 'prefix = "ctrl+a"')
        self.assertNotEqual(changed, SOURCE)
        merged = tomllib.loads(module.merge(changed, live))
        self.assertEqual(merged["keys"]["prefix"], "ctrl+a")
        self.assertEqual(merged["theme"]["custom"], tomllib.loads(OMNIWM_TABLE)["theme"]["custom"])
        self.assertEqual(merged["theme"]["name"], tomllib.loads(SOURCE)["theme"]["name"])

    def test_text_after_the_last_key_stays_with_the_repository(self):
        live = "[theme.custom]\nred = \"#111111\"\n\n# live note\n[keys]\nprefix = \"x\"\n"
        source = "[theme.custom]\nred = \"#222222\"\n\n# repo note\n[keys]\nprefix = \"y\"\n"
        self.assertEqual(
            module.merge(source, live),
            "[theme.custom]\nred = \"#111111\"\n\n# repo note\n[keys]\nprefix = \"y\"\n",
        )

    def test_table_at_end_of_file_and_missing_tables(self):
        live = "[keys]\nprefix = \"x\"\n\n  [ theme . custom ]  # colors\nred = \"#111111\""
        source = "[keys]\nprefix = \"y\"\n"
        merged = module.merge(source, live)
        self.assertEqual(tomllib.loads(merged), {"keys": {"prefix": "y"}, "theme": {"custom": {"red": "#111111"}}})
        self.assertEqual(module.merge(SOURCE, "[keys]\nprefix = \"x\"\n"), SOURCE)

    def test_sync_replaces_a_link_and_leaves_an_up_to_date_file_alone(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            source = root / "source.toml"
            source.write_text(SOURCE)
            target = root / "herdr/config.toml"
            module.sync(source, target)
            self.assertEqual(target.read_text(), SOURCE)

            target.unlink()
            target.symlink_to(source)
            module.sync(source, target)
            self.assertFalse(target.is_symlink())
            self.assertEqual(target.read_text(), SOURCE)

            live = with_table(SOURCE, OMNIWM_TABLE)
            target.write_text(live)
            before = target.stat().st_ino
            module.sync(source, target)
            self.assertEqual(target.read_text(), live)
            self.assertEqual(target.stat().st_ino, before)
            self.assertEqual(list(target.parent.iterdir()), [target])


if __name__ == "__main__":
    unittest.main()
