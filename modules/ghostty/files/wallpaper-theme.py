#!/usr/bin/env python3
"""Write Ghostty's omniwm-light and omniwm-dark themes, the palette Neovim
reads, herdr's [theme.custom], OmniWM's border colors and the OmniShell theme
of its workspace bar from the macOS wallpaper.

A stand-in until the pinned OmniWM has App Theming, which writes the same
files (docs/notes/macos-wallpaper-theming.md). matugen turns the wallpaper into
Material 3 roles; the terminal colors follow OmniWM's "Follow Palette" mapping.

Usage: wallpaper-theme.py --matugen MATUGEN [IMAGE]
Without IMAGE, the wallpaper macOS used most recently is read from its store.
"""

import argparse
import json
import os
from pathlib import Path
import plistlib
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
from urllib.parse import unquote, urlparse

WALLPAPER_INDEX = Path.home() / "Library/Application Support/com.apple.wallpaper/Store/Index.plist"
THEMES = Path.home() / ".config/ghostty/themes"
# Read by modules/nvim/files/lua/core/wallpaper-palette.lua, which watches the folder.
NVIM_PALETTE = Path.home() / ".config/theme/omniwm-palette"
# A regular file on the OmniWM rice (modules/herdr); a link into the Nix store elsewhere.
HERDR_CONFIG = Path.home() / ".config/herdr/config.toml"
HERDR_TABLE = re.compile(r"^[ \t]*\[[ \t]*theme[ \t]*\.[ \t]*custom[ \t]*\][ \t]*(#.*)?$")
# OmniWM picks up outside edits to its settings. Only the border colors are touched.
OMNIWM_SETTINGS = Path.home() / ".config/omniwm/settings.toml"
BORDER_ROLES = {"borders.color": "primary", "borders.gradient.start": "primary", "borders.gradient.end": "tertiary"}
# An OmniShell theme in the top shell folder, which OmniWM searches before the
# style's own and reloads on change. Selected once with `omniwmctl shell theme matugen`.
SHELL_THEME = Path.home() / ".config/omniwm/shell/themes/matugen.toml"
# The roles OmniWM 0.8.0 fills from its own wallpaper palette (ShellMaterialPalette.swift);
# the rest keep the native defaults.
SHELL_ROLES = {
    "background": "background",
    "surface": "surface_container",
    "elevatedSurface": "surface_container_high",
    "highestSurface": "surface_container_highest",
    "foreground": "on_surface",
    "secondaryForeground": "on_surface_variant",
    "mutedForeground": "outline",
    "border": "outline_variant",
    "accent": "primary",
    "accentForeground": "on_primary",
    "accentContainer": "primary_container",
    "accentContainerForeground": "on_primary_container",
    "secondaryAccent": "secondary",
    "secondaryContainer": "secondary_container",
    "secondaryContainerForeground": "on_secondary_container",
    "tertiaryAccent": "tertiary",
    "tertiaryContainer": "tertiary_container",
    "tertiaryContainerForeground": "on_tertiary_container",
    "error": "error",
    "focus": "primary",
    "shadow": "shadow",
}
HEADER = "# Generated from the wallpaper by modules/ghostty/files/wallpaper-theme.py."
OMNIWM_HEADER = "# Generated by OmniWM"
MIN_CONTRAST = 4.5


def current_wallpaper(index):
    """The image of the desktop macOS showed last, or None when it is not an image file.

    The store keeps one "Desktop" entry per space and display, each with the
    time it was last shown.
    """
    desktops = []

    def collect(node):
        if isinstance(node, dict):
            desktop = node.get("Desktop")
            if isinstance(desktop, dict) and "LastUse" in desktop:
                desktops.append(desktop)
            for value in node.values():
                collect(value)

    collect(index)
    if not desktops:
        return None
    choices = max(desktops, key=lambda desktop: desktop["LastUse"]).get("Content", {}).get("Choices") or [{}]
    if choices[0].get("Provider") != "com.apple.wallpaper.choice.image":
        return None
    try:
        url = plistlib.loads(choices[0]["Configuration"])["url"]["relative"]
    except (KeyError, TypeError, plistlib.InvalidFileException):
        return None
    parsed = urlparse(url)
    return Path(unquote(parsed.path)) if parsed.scheme == "file" else None


def channels(color):
    return [int(color[i : i + 2], 16) for i in (1, 3, 5)]


def blend(start, end, amount):
    return "#" + "".join(f"{round(a + (b - a) * amount):02x}" for a, b in zip(channels(start), channels(end)))


def luminance(color):
    linear = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in (v / 255 for v in channels(color))]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(first, second):
    high, low = sorted((luminance(first), luminance(second)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def readable(color, background, foreground):
    """The color, moved toward the foreground until it reads on the background."""
    for step in range(11):
        candidate = blend(color, foreground, step / 10)
        if contrast(candidate, background) >= MIN_CONTRAST:
            return candidate
    return foreground


def terminal_palette(colors, mode):
    """The sixteen terminal colors for one mode of matugen's colors."""
    role = lambda name: colors[name][mode]["color"].lower()
    background, foreground = role("surface"), role("on_surface")
    # Red is error, green the accent, yellow and blue the other two accents;
    # magenta and cyan are lighter accents.
    normal = [
        role("error"),
        role("primary"),
        role("secondary"),
        role("tertiary"),
        blend(role("primary"), foreground, 0.4),
        blend(role("secondary"), foreground, 0.4),
    ]
    palette = (
        [role("surface_container_highest")]
        + normal
        + [role("on_surface_variant"), role("outline")]
        + [blend(color, foreground, 0.3) for color in normal]
        + [foreground]
    )
    return palette[:1] + [readable(color, background, foreground) for color in palette[1:]]


def theme(colors, mode):
    """Ghostty theme text for one mode of matugen's colors."""
    role = lambda name: colors[name][mode]["color"].lower()
    palette = terminal_palette(colors, mode)
    lines = [
        HEADER,
        f"background = {role('surface')}",
        f"foreground = {role('on_surface')}",
        f"cursor-color = {role('primary')}",
        f"cursor-text = {role('on_primary')}",
        f"selection-background = {role('primary_container')}",
        f"selection-foreground = {role('on_primary_container')}",
    ] + [f"palette = {index}={color}" for index, color in enumerate(palette)]
    return "\n".join(lines) + "\n"


def nvim_palette(colors, mode):
    """The roles OmniWM's nvim-palette template renders, for one mode."""
    role = lambda name: colors[name][mode]["color"].lower()
    palette = terminal_palette(colors, mode)
    roles = {
        "mode": mode,
        "background": role("surface"),
        "surface": role("surface_container"),
        "accentContainer": role("primary_container"),
        "foreground": role("on_surface"),
        "secondaryForeground": palette[7],
        "mutedForeground": palette[8],
        **{f"ansi{index}": palette[index] for index in (1, 2, 3, 4, 5, 6, 12)},
        # base16's orange sits between red and yellow.
        "base09": blend(palette[1], palette[3], 0.5),
    }
    return HEADER + "\n" + "".join(f"{name}={value}\n" for name, value in roles.items())


def herdr_table(colors, mode):
    """herdr's [theme.custom], with the keys OmniWM's herdr template sets."""
    role = lambda name: colors[name][mode]["color"].lower()
    palette = terminal_palette(colors, mode)
    # The surfaces stay "reset" so herdr keeps the terminal's background and transparency.
    values = {
        "accent": role("primary"),
        "panel_bg": "reset",
        "surface0": "reset",
        "surface1": "reset",
        "surface_dim": "reset",
        "active_row_bg": role("primary_container"),
        "selection_bg": role("primary_container"),
        "overlay0": palette[8],
        "overlay1": palette[7],
        "text": role("on_surface"),
        "subtext0": palette[7],
        "red": palette[1],
        "green": palette[2],
        "yellow": palette[3],
        "peach": palette[11],
        "blue": palette[4],
        "mauve": palette[5],
        "teal": palette[6],
    }
    return "[theme.custom]\n" + HEADER + "\n" + "".join(f'{name} = "{value}"\n' for name, value in values.items())


def shell_theme(colors):
    """The OmniShell theme for both modes; OmniWM picks the one macOS shows."""
    tables = []
    for mode in ("light", "dark"):
        rows = "".join(f'{name} = "{colors[role][mode]["color"].upper()}"\n' for name, role in SHELL_ROLES.items())
        tables.append(f"[{mode}]\n{rows}")
    return HEADER + "\n\n" + "\n".join(tables)


def table_span(lines):
    """Line range of [theme.custom], header through last key, as modules/herdr/files/sync-config.py keeps it."""
    start = next((i for i, line in enumerate(lines) if HERDR_TABLE.match(line.rstrip("\r\n"))), None)
    if start is None:
        return None
    end = start + 1
    for i in range(start + 1, len(lines)):
        stripped = lines[i].strip()
        if stripped.startswith("["):
            break
        if stripped and not stripped.startswith("#"):
            end = i + 1
    return start, end


def with_herdr_table(text, table):
    """The config with its color table replaced, or None when OmniWM wrote that table."""
    lines = text.splitlines(keepends=True)
    span = table_span(lines)
    if span is None:
        return text + ("" if not text or text.endswith("\n\n") else "\n" if text.endswith("\n") else "\n\n") + table
    if any(line.startswith(OMNIWM_HEADER) for line in lines[span[0] : span[1]]):
        return None
    return "".join(lines[: span[0]]) + table + "".join(lines[span[1] :])


def with_border_colors(text, colors, mode):
    """OmniWM's settings with the border colors replaced, or None when they are not laid out as expected."""
    lines = text.splitlines(keepends=True)
    for table, role in BORDER_ROLES.items():
        try:
            start = next(i for i, line in enumerate(lines) if line.strip() == f"[{table}]")
        except StopIteration:
            return None
        end = next((i for i in range(start + 1, len(lines)) if lines[i].lstrip().startswith("[")), len(lines))
        values = dict(zip(("red", "green", "blue"), channels(colors[role][mode]["color"])))
        for i in range(start + 1, end):
            name = lines[i].split("=")[0].strip()
            if name in values:
                lines[i] = f"{name} = {round(values.pop(name) / 255, 6)!r}\n"
        if values:
            return None
    result = "".join(lines)

    def without_borders(settings):
        try:
            parsed = tomllib.loads(settings)
        except tomllib.TOMLDecodeError:
            return None
        for table in BORDER_ROLES:
            node = parsed
            for key in table.split("."):
                node = node[key]
            for name in ("red", "green", "blue"):
                del node[name]
        return parsed

    # Everything else has to come through untouched.
    rest = without_borders(result)
    return result if rest is not None and rest == without_borders(text) else None


def replace_settings(path, colors, mode):
    """Recolor OmniWM's borders. Returns whether the file changed; leaves it alone when unsure."""
    if not path.is_file() or path.is_symlink():
        return False
    original = path.read_text()
    changed = with_border_colors(original, colors, mode)
    if changed is None or changed == original:
        return False
    backup = path.with_name(path.name + ".before-wallpaper-borders")
    if not backup.exists():
        backup.write_text(original)
        backup.chmod(0o600)
    # OmniWM saves this file itself; never overwrite a save that landed meanwhile.
    return atomic_write(path, changed, path.stat().st_mode & 0o777, expected=original)


def atomic_write(path, text, mode, expected=None):
    """Write text to path in one step. With expected, only while the file still holds it."""
    staged = None
    try:
        with tempfile.NamedTemporaryFile("w", dir=path.parent, delete=False) as output:
            staged = Path(output.name)
            output.write(text)
        staged.chmod(mode)
        if expected is not None and path.read_text() != expected:
            return False
        os.replace(staged, path)
    finally:
        if staged is not None:
            staged.unlink(missing_ok=True)
    return True


def replace(path, text):
    """Replace the file in one step. Returns whether anything changed."""
    if path.exists() and path.read_text() == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    return atomic_write(path, text, 0o644)


def write_themes(colors, themes, palette, herdr, settings, shell, mode):
    """Write both Ghostty themes and the bar theme, and Neovim's palette, herdr's table and OmniWM's borders for the current mode.

    Returns the apps to reload, or None, writing nothing, when OmniWM owns the
    files: its themes and its herdr table carry its header, and its palette is
    any that lacks ours.
    """
    targets = {name: themes / f"omniwm-{name}" for name in ("light", "dark")}
    for target in targets.values():
        if target.exists() and target.read_text().startswith(OMNIWM_HEADER):
            return None
    if palette.exists() and not palette.read_text().startswith(HEADER):
        return None
    herdr_text = None
    if herdr.is_file() and not herdr.is_symlink():
        herdr_text = with_herdr_table(herdr.read_text(), herdr_table(colors, mode))
        if herdr_text is None:
            return None
    replace(palette, nvim_palette(colors, mode))
    changed = set()
    if any([replace(target, theme(colors, name)) for name, target in targets.items()]):
        changed.add("ghostty")
    if herdr_text is not None and replace(herdr, herdr_text):
        changed.add("herdr")
    if replace_settings(settings, colors, mode):
        changed.add("borders")
    if replace(shell, shell_theme(colors)):
        changed.add("bar")
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--matugen", required=True)
    parser.add_argument("image", nargs="?", type=Path)
    arguments = parser.parse_args()

    image = arguments.image
    if image is None:
        image = current_wallpaper(plistlib.loads(WALLPAPER_INDEX.read_bytes()))
        if image is None:
            sys.exit("The current wallpaper is not an image file; pass one as an argument.")
    if not image.is_file():
        # macOS keeps showing its own copy, which sits in a folder this script may not read.
        sys.exit(f"{image} is gone; set the wallpaper from a file that stays, such as one in ~/Pictures/Wallpapers.")
    result = subprocess.run(
        [arguments.matugen, "image", str(image), "--prefer", "saturation", "--json", "hex", "--dry-run", "--quiet"],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        sys.exit(f"matugen could not read {image}: {result.stderr.strip()}")
    # macOS has no AppleInterfaceStyle while it is light.
    appearance = subprocess.run(["/usr/bin/defaults", "read", "-g", "AppleInterfaceStyle"], capture_output=True, text=True)
    mode = "dark" if appearance.stdout.strip() == "Dark" else "light"
    changed = write_themes(json.loads(result.stdout)["colors"], THEMES, NVIM_PALETTE, HERDR_CONFIG, OMNIWM_SETTINGS, SHELL_THEME, mode)
    if changed is None:
        sys.exit("OmniWM App Theming owns the themes now; remove this stand-in.")
    if "ghostty" in changed:
        # Ghostty 1.2 and newer reload their config on SIGUSR2.
        subprocess.run(["/usr/bin/pkill", "-USR2", "-x", "ghostty"], check=False)
    if "herdr" in changed:
        # launchd starts this with a bare PATH. Without a running server there is nothing to reload.
        profile = f"/etc/profiles/per-user/{Path.home().name}/bin"
        command = shutil.which("herdr", path=os.pathsep.join([os.environ.get("PATH", ""), profile]))
        if command:
            subprocess.run([command, "server", "reload-config"], capture_output=True, check=False)
    print(f"{image}: {', '.join(sorted(changed)) + ' updated' if changed else 'unchanged'}")


if __name__ == "__main__":
    main()
