#!/usr/bin/env python3
"""Write Ghostty's omniwm-light and omniwm-dark themes, and the palette Neovim
reads, from the macOS wallpaper.

A stand-in until the pinned OmniWM has App Theming, which writes the same
files (docs/notes/macos-wallpaper-theming.md). matugen turns the wallpaper into
Material 3 roles; the terminal colors follow OmniWM's "Follow Palette" mapping.

Usage: wallpaper-theme.py --matugen MATUGEN [IMAGE]
Without IMAGE, the wallpaper macOS used most recently is read from its store.
"""

import argparse
import json
import os
from pathlib import Path
import plistlib
import subprocess
import sys
import tempfile
from urllib.parse import unquote, urlparse

WALLPAPER_INDEX = Path.home() / "Library/Application Support/com.apple.wallpaper/Store/Index.plist"
THEMES = Path.home() / ".config/ghostty/themes"
# Read by modules/nvim/files/lua/core/wallpaper-palette.lua, which watches the folder.
NVIM_PALETTE = Path.home() / ".config/theme/omniwm-palette"
HEADER = "# Generated from the wallpaper by modules/ghostty/files/wallpaper-theme.py."
OMNIWM_HEADER = "# Generated by OmniWM"
MIN_CONTRAST = 4.5


def current_wallpaper(index):
    """The image of the desktop macOS showed last, or None when it is not an image file.

    The store keeps one "Desktop" entry per space and display, each with the
    time it was last shown.
    """
    desktops = []

    def collect(node):
        if isinstance(node, dict):
            desktop = node.get("Desktop")
            if isinstance(desktop, dict) and "LastUse" in desktop:
                desktops.append(desktop)
            for value in node.values():
                collect(value)

    collect(index)
    if not desktops:
        return None
    choices = max(desktops, key=lambda desktop: desktop["LastUse"]).get("Content", {}).get("Choices") or [{}]
    if choices[0].get("Provider") != "com.apple.wallpaper.choice.image":
        return None
    try:
        url = plistlib.loads(choices[0]["Configuration"])["url"]["relative"]
    except (KeyError, TypeError, plistlib.InvalidFileException):
        return None
    parsed = urlparse(url)
    return Path(unquote(parsed.path)) if parsed.scheme == "file" else None


def channels(color):
    return [int(color[i : i + 2], 16) for i in (1, 3, 5)]


def blend(start, end, amount):
    return "#" + "".join(f"{round(a + (b - a) * amount):02x}" for a, b in zip(channels(start), channels(end)))


def luminance(color):
    linear = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in (v / 255 for v in channels(color))]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(first, second):
    high, low = sorted((luminance(first), luminance(second)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def readable(color, background, foreground):
    """The color, moved toward the foreground until it reads on the background."""
    for step in range(11):
        candidate = blend(color, foreground, step / 10)
        if contrast(candidate, background) >= MIN_CONTRAST:
            return candidate
    return foreground


def terminal_palette(colors, mode):
    """The sixteen terminal colors for one mode of matugen's colors."""
    role = lambda name: colors[name][mode]["color"].lower()
    background, foreground = role("surface"), role("on_surface")
    # Red is error, green the accent, yellow and blue the other two accents;
    # magenta and cyan are lighter accents.
    normal = [
        role("error"),
        role("primary"),
        role("secondary"),
        role("tertiary"),
        blend(role("primary"), foreground, 0.4),
        blend(role("secondary"), foreground, 0.4),
    ]
    palette = (
        [role("surface_container_highest")]
        + normal
        + [role("on_surface_variant"), role("outline")]
        + [blend(color, foreground, 0.3) for color in normal]
        + [foreground]
    )
    return palette[:1] + [readable(color, background, foreground) for color in palette[1:]]


def theme(colors, mode):
    """Ghostty theme text for one mode of matugen's colors."""
    role = lambda name: colors[name][mode]["color"].lower()
    palette = terminal_palette(colors, mode)
    lines = [
        HEADER,
        f"background = {role('surface')}",
        f"foreground = {role('on_surface')}",
        f"cursor-color = {role('primary')}",
        f"cursor-text = {role('on_primary')}",
        f"selection-background = {role('primary_container')}",
        f"selection-foreground = {role('on_primary_container')}",
    ] + [f"palette = {index}={color}" for index, color in enumerate(palette)]
    return "\n".join(lines) + "\n"


def nvim_palette(colors, mode):
    """The roles OmniWM's nvim-palette template renders, for one mode."""
    role = lambda name: colors[name][mode]["color"].lower()
    palette = terminal_palette(colors, mode)
    roles = {
        "mode": mode,
        "background": role("surface"),
        "surface": role("surface_container"),
        "accentContainer": role("primary_container"),
        "foreground": role("on_surface"),
        "secondaryForeground": palette[7],
        "mutedForeground": palette[8],
        **{f"ansi{index}": palette[index] for index in (1, 2, 3, 4, 5, 6, 12)},
        # base16's orange sits between red and yellow.
        "base09": blend(palette[1], palette[3], 0.5),
    }
    return HEADER + "\n" + "".join(f"{name}={value}\n" for name, value in roles.items())


def replace(path, text):
    """Replace the file in one step. Returns whether anything changed."""
    if path.exists() and path.read_text() == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    staged = None
    try:
        with tempfile.NamedTemporaryFile("w", dir=path.parent, delete=False) as output:
            staged = Path(output.name)
            output.write(text)
        staged.chmod(0o644)
        os.replace(staged, path)
    finally:
        if staged is not None:
            staged.unlink(missing_ok=True)
    return True


def write_themes(colors, themes, palette, mode):
    """Write both Ghostty themes and Neovim's palette for the current mode.

    Returns whether a Ghostty theme changed, or None, writing nothing, when
    OmniWM owns the files: its themes carry its header, and its palette is
    any that lacks ours.
    """
    targets = {name: themes / f"omniwm-{name}" for name in ("light", "dark")}
    for target in targets.values():
        if target.exists() and target.read_text().startswith(OMNIWM_HEADER):
            return None
    if palette.exists() and not palette.read_text().startswith(HEADER):
        return None
    replace(palette, nvim_palette(colors, mode))
    return any([replace(target, theme(colors, name)) for name, target in targets.items()])


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--matugen", required=True)
    parser.add_argument("image", nargs="?", type=Path)
    arguments = parser.parse_args()

    image = arguments.image
    if image is None:
        image = current_wallpaper(plistlib.loads(WALLPAPER_INDEX.read_bytes()))
        if image is None:
            sys.exit("The current wallpaper is not an image file; pass one as an argument.")
    if not image.is_file():
        # macOS keeps showing its own copy, which sits in a folder this script may not read.
        sys.exit(f"{image} is gone; set the wallpaper from a file that stays, such as one in ~/Pictures/Wallpapers.")
    result = subprocess.run(
        [arguments.matugen, "image", str(image), "--prefer", "saturation", "--json", "hex", "--dry-run", "--quiet"],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        sys.exit(f"matugen could not read {image}: {result.stderr.strip()}")
    # macOS has no AppleInterfaceStyle while it is light.
    appearance = subprocess.run(["/usr/bin/defaults", "read", "-g", "AppleInterfaceStyle"], capture_output=True, text=True)
    mode = "dark" if appearance.stdout.strip() == "Dark" else "light"
    changed = write_themes(json.loads(result.stdout)["colors"], THEMES, NVIM_PALETTE, mode)
    if changed is None:
        sys.exit("OmniWM App Theming owns the themes now; remove this stand-in.")
    if changed:
        # Ghostty 1.2 and newer reload their config on SIGUSR2.
        subprocess.run(["/usr/bin/pkill", "-USR2", "-x", "ghostty"], check=False)
    print(f"{image}: {'updated' if changed else 'unchanged'}")


if __name__ == "__main__":
    main()
